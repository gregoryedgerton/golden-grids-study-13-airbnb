#!/usr/bin/env python3
"""Draw Provincetown from OpenStreetMap data (ODbL) as SVG paths for src/map.ts.

    python3 captures/map.py        # reads captures/osm/raw.json, writes src/map.ts

raw.json is an Overpass API answer for the query in captures/osm/q.txt. The
coastline ways are joined into one line (land is on its left), cut where it
leaves the east edge and closed there; streets, wharves, ponds, woods and
beaches are simplified and projected with the same plain projection, which
src/map.ts also exports so a pin can be placed by latitude and longitude.
"""
import json, math
from pathlib import Path
ROOT = Path(__file__).parent.parent
d = json.loads((ROOT / "captures/osm/raw.json").read_text())["elements"]
LON0, LAT0, EAST = -70.262, 42.092, -70.118
K = 1000 / ((EAST - LON0) * math.cos(math.radians(42.05)))          # 1000 units across
COS = math.cos(math.radians(42.05))
def P(lat, lon): return ((lon - LON0) * COS * K, (LAT0 - lat) * K)
def pts(e): return [P(g["lat"], g["lon"]) for g in e["geometry"]]

def simplify(p, tol):
    if len(p) < 3: return p
    keep = [False] * len(p); keep[0] = keep[-1] = True; stack = [(0, len(p) - 1)]
    while stack:
        a, b = stack.pop(); (x1, y1), (x2, y2) = p[a], p[b]; dx, dy = x2 - x1, y2 - y1; L = math.hypot(dx, dy) or 1e-9
        best, bi = 0, None
        for i in range(a + 1, b):
            dist = abs(dy * (p[i][0] - x1) - dx * (p[i][1] - y1)) / L
            if dist > best: best, bi = dist, i
        if bi is not None and best > tol: keep[bi] = True; stack += [(a, bi), (bi, b)]
    return [q for q, k in zip(p, keep) if k]
def path(p, close=False): return "M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in p) + ("Z" if close else "")

# Coastline: join the ways end to start.
ways = {e["id"]: e["geometry"] for e in d if e.get("tags", {}).get("natural") == "coastline"}
start = {(round(g[0]["lat"], 7), round(g[0]["lon"], 7)): i for i, g in ways.items()}
ends = {(round(g[-1]["lat"], 7), round(g[-1]["lon"], 7)) for g in ways.values()}
first = next(i for i, g in ways.items() if (round(g[0]["lat"], 7), round(g[0]["lon"], 7)) not in ends)
chain, cur = [], first
while cur is not None:
    g = ways.pop(cur); chain += g if not chain else g[1:]
    cur = start.get((round(g[-1]["lat"], 7), round(g[-1]["lon"], 7))); cur = cur if cur in ways else None
inside = [i for i, g in enumerate(chain) if g["lon"] <= EAST]
coast = [P(g["lat"], g["lon"]) for g in chain[inside[0]:inside[-1] + 1]]
land = path(simplify(coast, 0.35), True)

def tag(e, k): return e.get("tags", {}).get(k)
MAJOR = {"Commercial Street", "Bradford Street", "Bradford Street Extension", "Province Lands Road", "Race Point Road", "Conwell Street", "Shank Painter Road", "Snail Road", "Shore Road"}
def line(e): return path(simplify(pts(e), 0.3))
def area(e): return path(simplify(pts(e), 0.5), True)
hwy = [e for e in d if e["type"] == "way" and tag(e, "highway") and all(g["lon"] <= EAST for g in e["geometry"])]
route6 = "".join(line(e) for e in hwy if tag(e, "highway") == "trunk")
major = "".join(line(e) for e in hwy if tag(e, "name") in MAJOR)
minor = "".join(line(e) for e in hwy if tag(e, "highway") in ("residential", "unclassified", "tertiary", "secondary", "living_street", "pedestrian") and tag(e, "name") not in MAJOR)
piers = "".join((area(e) if e["geometry"][0] == e["geometry"][-1] else line(e)) for e in d if e["type"] == "way" and tag(e, "man_made") in ("pier", "breakwater"))
def big(e, a=30):
    p = pts(e); xs = [x for x, _ in p]; ys = [y for _, y in p]
    return e["geometry"][0] == e["geometry"][-1] and (max(xs) - min(xs)) * (max(ys) - min(ys)) > a and all(g["lon"] <= EAST for g in e["geometry"])
water = "".join(area(e) for e in d if e["type"] == "way" and tag(e, "natural") == "water" and big(e))
for r in (e for e in d if e["type"] == "relation" and tag(e, "natural") == "water"):
    for m in r["members"]:
        if m.get("role") == "outer" and "geometry" in m:
            p = [P(g["lat"], g["lon"]) for g in m["geometry"]]
            if all(g["lon"] <= EAST for g in m["geometry"]): water += path(simplify(p, 0.5), True)
wood = "".join(area(e) for e in d if e["type"] == "way" and tag(e, "natural") == "wood" and big(e))
sand = "".join(area(e) for e in d if e["type"] == "way" and tag(e, "natural") in ("beach", "sand") and big(e, 60))

# Commercial Street, west to east, as a list of points to place pins along.
com = sorted({(g["lon"], g["lat"]) for e in hwy if tag(e, "name") == "Commercial Street" for g in e["geometry"]})
brad = sorted({(g["lon"], g["lat"]) for e in hwy if tag(e, "name") in ("Bradford Street", "Bradford Street Extension") for g in e["geometry"]})
(ROOT / "captures/osm/streets.json").write_text(json.dumps({"commercial": com, "bradford": brad}))

out = f'''// Generated by captures/map.py from OpenStreetMap data (© OpenStreetMap contributors, ODbL). Do not edit by hand.
// A plain projection: 1000 units from {LON0}° to {EAST}° of longitude, north at the top.
export const MAP = {{ lon0: {LON0}, lat0: {LAT0}, k: {K:.3f}, cos: {COS:.6f} }};
export function project(lat: number, lon: number): [number, number] {{ return [(lon - MAP.lon0) * MAP.cos * MAP.k, (MAP.lat0 - lat) * MAP.k]; }}
export const LAND = "{land}";
export const SAND = "{sand}";
export const WOOD = "{wood}";
export const WATER = "{water}";
export const ROUTE6 = "{route6}";
export const MAJOR = "{major}";
export const MINOR = "{minor}";
export const PIERS = "{piers}";
'''
(ROOT / "src/map.ts").write_text(out)
print({k: len(v) for k, v in dict(land=land, sand=sand, wood=wood, water=water, route6=route6, major=major, minor=minor, piers=piers).items()}, len(com), len(brad))
print("height units", (LAT0 - 42.015) * K)
svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 {(LAT0-42.015)*K:.0f}" width="1400"><rect width="100%" height="100%" fill="#cfe8f5"/><path d="{land}" fill="#f3f1ea"/><path d="{sand}" fill="#f6edc9"/><path d="{wood}" fill="#d5e8cb"/><path d="{water}" fill="#cfe8f5"/><path d="{minor}" fill="none" stroke="#fff" stroke-width="1.2"/><path d="{route6}" fill="none" stroke="#f5d48a" stroke-width="2.4"/><path d="{major}" fill="none" stroke="#fff" stroke-width="2.4"/><path d="{piers}" fill="#e9e6dc" stroke="#e9e6dc" stroke-width="1.5"/></svg>'
(ROOT / "captures/osm/preview.svg").write_text(svg)
